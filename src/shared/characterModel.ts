/**
 * Из чего собран человек: какая модель служит телом и откуда взяты
 * недостающие части.
 *
 * Зачем это отдельным описанием, а не одной моделью на человека. Набор
 * Quaternius Ultimate Modular — это двадцать одна модель, разложенная
 * на четыре узла (`*_Head`, `*_Body`, `*_Legs`, `*_Feet`), и все они
 * сидят на одном скелете из 62 костей с одинаковыми именами. Поэтому
 * часть из любого файла садится на скелет любого другого, а нужный
 * человек собирается перестановкой: борода и грива Марея живут
 * в `men/Adventurer`, а его свитер — в `men/Casual_Hoodie`. Готовой
 * модели ни одного из шестерых в наборе нет и быть не может.
 *
 * Файл лежит в src/shared по той же причине, что и appearance.ts:
 * описание нужно и контенту (кто как выглядит), и рендеру (как это
 * нарисовать), а стрелки зависимостей идут только вниз.
 *
 * Здесь только данные и чистые функции. Как именно части сшиваются
 * и красятся — в src/render/character/gltfAssembly.ts.
 */

/** Мужской или женский набор. Части переставляются и между ними. */
export type ModelPack = 'men' | 'women'

/**
 * Часть тела как отдельный узел модели.
 *
 * `Pants` — не опечатка: у `men/Farmer` ноги названы `Farmer_Pants`
 * вместо `_Legs`. Мы этой модели не берём, но правило разбора имён
 * не должно спотыкаться, если её когда-нибудь возьмут.
 */
export type PartSlot = 'Head' | 'Body' | 'Legs' | 'Feet' | 'Pants'

export const PART_SLOTS: readonly PartSlot[] = ['Head', 'Body', 'Legs', 'Feet', 'Pants']

/**
 * Чем материал стал на человеке.
 *
 * Материалы в наборе названы по смыслу (`Skin`, `Hair`, `Eyebrows`,
 * `Suit`, `Purple`), но одно и то же имя в разных файлах значит разное:
 * `Grey` — то футболка, то ботинки. Поэтому роль вычисляется не по имени,
 * а по тому, в какой части тела материал лежит и много ли на него
 * приходится поверхности.
 */
export type MaterialRole = 'skin' | 'hair' | 'top' | 'bottom' | 'shoes' | 'keep'

export interface ModelRef {
  pack: ModelPack
  /** Имя файла без расширения, как в наборе: `Casual_2`, `SciFi`. */
  name: string
}

export interface CharacterModel {
  /** Файл, дающий скелет и всё, что не переопределено. */
  base: ModelRef
  /** Части, взятые из других файлов. */
  parts?: Readonly<Partial<Record<PartSlot, ModelRef>>>
  /**
   * Материалы, которые общее правило разбирает неверно.
   *
   * Правило считает главным материалом части тот, на который приходится
   * больше всего поверхности. Оно ошибается там, где у части есть
   * крупная деталь не по делу: на голове `women/SciFi` есть синяя
   * накладка от скафандра, и её надо красить как волосы, а не оставлять
   * синей посреди причёски.
   */
  roles?: Readonly<Record<string, MaterialRole>>
}

/** Где лежат модели в public/. */
export const CHARACTER_MODEL_DIR = '/models/characters'

/**
 * Общий файл анимаций.
 *
 * Клипы адресуют кости по имени, а скелет у всех моделей набора один,
 * поэтому файл нужен ровно один на всех. В исходниках Quaternius
 * двадцать четыре клипа скопированы в каждую из двадцати одной модели —
 * при шести персонажах это было бы полтора мегабайта одного и того же.
 */
export const CHARACTER_ANIMATIONS_URL = `${CHARACTER_MODEL_DIR}/animations.glb`

/** Клип спокойного стояния. */
export const IDLE_CLIP = 'Idle'
/** Клип ходьбы. Шагает на месте: движет персонажа симуляция, а не клип. */
export const WALK_CLIP = 'Walk'

export function modelUrl(ref: ModelRef): string {
  return `${CHARACTER_MODEL_DIR}/${ref.pack}/${ref.name}.glb`
}

/**
 * Все файлы, нужные одному человеку: тело, доноры частей и анимации.
 *
 * Порядок постоянный, а повторы убраны: голову и ноги Марей берёт
 * из разных файлов, а Долгоруков и Павлов делят одно тело — грузить
 * его дважды незачем, да и загрузчик отдаст один и тот же разбор.
 */
export function characterModelUrls(model: CharacterModel): string[] {
  const urls = [modelUrl(model.base)]
  for (const slot of PART_SLOTS) {
    const ref = model.parts?.[slot]
    if (ref) urls.push(modelUrl(ref))
  }
  urls.push(CHARACTER_ANIMATIONS_URL)
  return [...new Set(urls)]
}
