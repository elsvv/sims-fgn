import { MAREY_RESTROOM } from './marey-restroom'

/**
 * Многошаговые сцены игры.
 *
 * В отличие от коротких разговоров в коридоре (см. nodes.ts), сцена — это
 * не обмен репликами, а положение, в которое вы оба попали. Поэтому у неё
 * есть место и одноразовость: короткий разговор можно завести когда угодно
 * и сколько угодно раз, сцену — нет.
 *
 * «Марей в туалете» привязана к туалетам второго этажа и играется один раз.
 * Застать его там можно только по-настоящему: он заходит туда перед своей
 * парой (см. content/people/npcs.ts) и стоит внутри около двадцати пяти
 * игровых минут. Не успели сегодня — попробуете перед следующей его парой;
 * успели — сцена сыграна, и второй раз ловить того же человека у той же
 * раковины было бы уже не случайностью, а засадой.
 */
export const DIALOGUE_CHAINS: ChainCatalog = {
  [MAREY_RESTROOM.id]: {
    chain: MAREY_RESTROOM,
    room: 'туалеты',
    once: true,
  },
}
