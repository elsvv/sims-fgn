/**
 * Разговоры с преподавателями: по два узла на каждого из шести.
 * Первый — случайная встреча в коридоре, второй — разговор по существу
 * курса. Какой из двух откроется, решает dialogueNodeFor: пока вы друг
 * другу никто, здороваются; дальше говорят о деле.
 *
 * Пометки над репликами те же, что в people/teachers.ts:
 * — [источник] с указанием файла и раздела, если реплика взята дословно
 *   или почти дословно из публичных текстов;
 * — [допущение], если она написана нами в том же голосе и цитатой не является.
 * Пометки живут в комментариях: игрок видит реплику, а не наш аппарат.
 *
 * Правила, по которым собран каждый узел, — их держит nodes.test.ts:
 * 1. Не меньше трёх ответов, и хотя бы один без единого условия. Иначе
 *    у игрока однажды откроется пустое меню.
 * 2. Ответы различаются по последствиям: осторожный (безопасный, иногда
 *    чему-то учит), содержательный (требует навыка или прочитанной книги,
 *    даёт уважение) и дерзкий (симпатия в обмен на уважение).
 * 3. Сдвиг по шкале традиций у содержательного ответа направлен туда, где
 *    стоит сам преподаватель, у дерзкого — в противоположную сторону.
 *    Всеобщим любимцем стать нельзя, и видно это должно быть уже здесь.
 *
 * Навыки в осторожных ответах растут не для щедрости: без этого лесенка
 * не запускается. Навыки начинаются с нуля, а содержательный ответ требует
 * двойки — значит, первые двойки надо где-то взять, и берутся они из
 * простого «спросил и выслушал».
 */

