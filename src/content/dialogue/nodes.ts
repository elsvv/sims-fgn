export const DIALOGUE_NODES: DialogueCatalog = Object.fromEntries(
  NODES.map((node) => [node.id, node]),
)

/** Узлы одного собеседника в порядке знакомства: сначала коридорный. */
export function nodesOf(speakerId: string): DialogueNode[] {
  return NODES.filter((node) => node.speakerId === speakerId)
}

/**
 * Какой разговор начнётся при клике по человеку.
 *
 * Пока вы друг другу никто — здороваются; как только преподаватель вас
 * заметил, разговор переходит к делу. Порог берётся из уровня отношений,
 * а не из отдельного числа: «Незнакомы» — единственное состояние,
 * из которого нельзя начать говорить о курсе.
 */
export function dialogueNodeFor(
  speakerId: string,
  relationship: Relationship,
): string | null {
  const [greeting, course] = nodesOf(speakerId)
  if (!greeting) return null
  if (relationshipLevel(relationship) === 'stranger') return greeting.id
  return (course ?? greeting).id
}
