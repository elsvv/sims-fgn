/**
 * Внешность шестерых преподавателей.
 *
 * Единственное требование к этому файлу: силуэты должны различаться.
 * Игрок смотрит на этаж сверху под углом, с десяти метров, и подписи он
 * читать не должен — он должен узнавать людей по фигуре. Поэтому у каждого
 * разведены сразу четыре признака: рост, телосложение, цвет верха и то,
 * что на голове и лице (борода, очки, объём волос). Совпадения по одному
 * признаку допустимы, по двум — уже нет; за этим следит appearances.test.ts.
 *
 * Все описания опираются на разделы «[ВНЕШНОСТЬ]» отчётов — ссылка на
 * источник стоит над каждым. Домысла в цвете одежды нет: взят тот наряд,
 * в котором человека видели на фотографиях, а не придуманный «под палитру».
 * Где цвет всё-таки сдвинут, это сказано вслух и объяснено — таких мест
 * три, и все три про читаемость с игровой камеры, а не про вкус.
 *
 * Поле `model` говорит, из каких файлов набора Quaternius собирается
 * фигура: готовой модели ни одного из шестерых в наборе нет, и каждый
 * собирается перестановкой частей (см. src/shared/characterModel.ts
 * и research/assets-characters.md, §4). Тот же набор значений рисует
 * и капсульный человечек — запасной путь на случай, если файл не доедет,
 * и он `model` просто не смотрит.
 *
 * Чего набор не умеет и что поэтому опущено: цвет бровей отдельно от
 * волос, отдельный цвет бороды, узор на ткани, украшения, веснушки.
 * Текстур в наборе нет ни одной — только плоские цвета материалов.
 */

