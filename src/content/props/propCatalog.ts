/**
 * ПРО МОДЕЛИ. Каждый предмет знает, каким файлом он рисуется и как этот
 * файл сажать в клетку. Числа живут здесь, а не в компоненте рендера,
 * потому что это свойства предмета, а не свойства кода.
 *
 * Три правила, общие для всего набора Kenney и потому не повторяющиеся
 * в каждом предмете:
 *
 * 1. «Перёд» модели — это +Z. Проверено рендером всех девяти файлов
 *    с трёх сторон: дверные ручки, фасады холодильников, сиденье скамейки,
 *    чаша унитаза — всё смотрит в +Z. Поэтому `placement.rotation: 0`
 *    означает «предмет смотрит на юг», и поправочный угол нужен ровно
 *    одной модели — лестнице, у которой направление подъёма идёт вдоль X.
 * 2. Масштаб не задаётся числом. Он считается из измеренного габарита
 *    модели и габарита предмета (fitPropModel), поэтому подмена файла
 *    на другой не требует подбора коэффициента заново.
 * 3. Модель садится на пол по нижней грани измеренного габарита, а не
 *    по началу координат: у четырёх моделей набора начало координат стоит
 *    не в основании.
 */

