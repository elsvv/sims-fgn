import type { Needs } from '../needs/needs'
import type { SkillId } from '../player/Skills'

/** Насколько действие поднимает навык. */
export interface InteractionSkillGain {
  id: SkillId
  amount: number
}

/** Действие, которое можно совершить с предметом. */
export interface Interaction {
  id: string
  /** Подпись в меню, на русском. */
  label: string
  /** Сколько игровых минут занимает. */
  durationMinutes: number
  /** Как меняются нужды по завершении. */
  needDelta: Partial<Needs>
  /**
   * Что действие даёт навыкам. Нет списка — не даёт ничего.
   *
   * Ровно то же поле есть у карточки воскресенья (sim/daily/Weekend.ts),
   * и это не совпадение: окно между парами — такое же потраченное время,
   * что и выходной. Пока навык умел расти только по воскресеньям, все окна
   * модуля вместе стоили меньше одного воскресенья, и заниматься в них
   * было нечем — см. пункт 4 списка проблем.
   */
  skills?: readonly InteractionSkillGain[]
  /**
   * Сколько игровых минут работы уходит в ближайшее несданное эссе.
   * Ноль или отсутствие — действие, не имеющее к тексту отношения.
   */
  essayMinutes?: number
  /**
   * Идентификатор модификатора настроения, который навешивается по завершении.
   * Ссылка, а не сам модификатор: тексты живут в каталоге контента,
   * и sim о нём ничего не знает.
   */
  moodletId?: string
}

/** Габариты предмета в метрах. */
export interface PropSize {
  w: number
  d: number
  h: number
}

/** Точка или сдвиг в метрах. Свой тип: sim ничего не знает про three. */
export interface Vec3 {
  x: number
  y: number
  z: number
}

/**
 * Как модель вписывается в габарит предмета.
 *
 * `contain` — пропорции сохраняются, модель вписывается целиком и может
 * не заполнить габарит до края. Так ставится всё, у чего пропорции
 * читаются: скамейка, автомат, унитаз.
 *
 * `stretch` — каждая ось тянется до своего размера. Так ставится то,
 * что от растяжения не портится: плоские панели (доска, двери лифта)
 * и предметы, которые иначе не влезают в метровую клетку (парта шириной
 * 1.47 м в наборе Kenney). Растягивать модели этого набора безопасно:
 * UV-развёртки у них нет вовсе, текстуре нечего искажать.
 */
export type PropModelFit = 'contain' | 'stretch'

/**
 * Как модель стоит в клетке по горизонтали.
 * `center` — посередине; `back` — вплотную к дальнему краю клетки,
 * то есть спиной к стене, к которой предмет повёрнут задом.
 */
export type PropModelAlign = 'center' | 'back'

/**
 * Что перекрашивается в цвет предмета из каталога.
 *
 * `dominant` — только материал, на который приходится больше всего
 * треугольников. Предмет получает нужный цвет, а мелкие контрастные детали
 * (ручки, стекло, столешница) остаются как задумано автором модели.
 */
export type PropModelTint = 'none' | 'dominant' | 'all'

/**
 * Модель предмета и всё, что нужно, чтобы поставить её в клетку.
 *
 * Это данные, а не магические числа в компоненте рендера: модели Kenney
 * сделаны в своих единицах (1 юнит = 0.5 м), с собственным началом
 * координат и собственным направлением «вперёд». Каждое из этих трёх
 * расхождений правится отдельным полем, и правится в каталоге предметов,
 * где его видно рядом с габаритами.
 */
export interface PropModel {
  /** Путь к файлу от корня сайта: `/models/props/desk.glb`. */
  url: string
  fit: PropModelFit
  /** По умолчанию `center`. */
  align?: PropModelAlign
  /** Множитель к вычисленному масштабу. По умолчанию 1. */
  scale?: number
  /**
   * Сдвиг в метрах в системе координат предмета — до поворота размещения.
   * Считается от посадки на пол, поэтому `y: 0.75` — это «висит на стене
   * на высоте 75 см», а не «парит непонятно почему».
   */
  offset?: Partial<Vec3>
  /**
   * Поправка поворота вокруг вертикали, радианы. Складывается с поворотом
   * размещения. Нужна, когда модель смотрит не туда, куда ожидает планировка:
   * у набора Kenney «перёд» — это +Z, а, скажем, у лифта дверь должна
   * смотреть вдоль +X.
   */
  rotationOffset?: number
  /** По умолчанию `dominant`. */
  tint?: PropModelTint
}

/**
 * Чем рисуется предмет: моделью или прежним цветным боксом.
 *
 * Строка `'box'` — это явный выбор, а не отсутствие данных. Предмет без
 * модели должен быть назван вслух, иначе забытое поле не отличить
 * от осознанного решения; это сторожит тест propModels.test.ts.
 */
export type PropModelRef = PropModel | 'box'

export interface PropDefinition {
  kind: string
  /** Подпись в интерфейсе, на русском. */
  label: string
  size: PropSize
  /** Основной цвет в формате CSS hex. */
  color: string
  /** Делает ли предмет свою клетку непроходимой. */
  blocks: boolean
  /** Что можно сделать. Пустой список — предмет декоративный. */
  interactions: Interaction[]
  /**
   * Модель предмета либо явное `'box'`. Поле необязательное только ради
   * тестовых каталогов симуляции, которым до внешнего вида дела нет:
   * у каждого предмета настоящего каталога оно обязано быть заполнено.
   */
  model?: PropModelRef
}

export type PropCatalog = Record<string, PropDefinition>
