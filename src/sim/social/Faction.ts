/** Крайние точки шкалы философских традиций. */
export const ANALYTIC = -100
export const CONTINENTAL = 100

export function clampFaction(value: number): number {
  return Math.min(CONTINENTAL, Math.max(ANALYTIC, value))
}

export function factionLabel(value: number): string {
  if (value <= -70) return 'Убеждённый аналитик'
  if (value <= -30) return 'Скорее аналитик'
  if (value < 30) return 'Ещё не определился'
  if (value < 70) return 'Скорее континентальный'
  return 'Континентальный до мозга костей'
}

/**
 * Что позиция на шкале значит для того, кто её занял.
 *
 * Нужна эпилогу: голая подпись «Скорее аналитик» ничего не говорит о том,
 * как человек прожил модуль, а игра в конце обязана сказать именно это.
 * Трактовка написана изнутри — так, как студент описал бы себя сам.
 */
export function factionMeaning(value: number): string {
  if (value <= -70) {
    return 'Вы научились говорить посылками и выводами и перестали верить фразе, которую нельзя проверить. На семинарах по немецкой классике вас считают занудой, в А-121 — своим.'
  }
  if (value <= -30) {
    return 'Вы тянетесь к ясности: сначала определим термины, потом спорим. До лаборатории логики вы ещё не дошли, но дорогу туда уже знаете.'
  }
  if (value < 30) {
    return 'Вы не выбрали сторону. Это можно назвать открытостью, а можно — тем, что за модуль вас никто ни во что не втянул. Правда, скорее всего, посередине.'
  }
  if (value < 70) {
    return 'Вы читаете текст, а не пересказ, и уже слышите разницу. К формальным аргументам относитесь вежливо и без интереса.'
  }
  return 'Вы окончательно на континентальной стороне: медленное чтение, немецкие термины, недоверие к тому, что можно записать формулой. Долгоруков это заметил.'
}

/**
 * Насколько студент «свой» для преподавателя.
 * 1 — попал точно в позицию, 0 — на границе допуска, отрицательное — чужой.
 *
 * Именно поэтому всеобщим любимцем стать нельзя: приблизившись к одному
 * полюсу, неизбежно отдаляешься от другого.
 */
export function affinity(position: number, tolerance: number, playerValue: number): number {
  const safeTolerance = Math.max(1, tolerance)
  const distance = Math.abs(position - playerValue)
  return Math.max(-1, 1 - distance / safeTolerance)
}

/**
 * Множитель к приросту уважения.
 * Даже полный чужак может заслужить уважение — просто вчетверо медленнее.
 */
export function affinityBonus(affinityValue: number): number {
  return 0.25 + (affinityValue + 1) * 0.625
}
