import type { Vec2 } from '../../sim/types'

/**
 * Громкость по расстоянию.
 *
 * Мир трёхмерный, и кофейный автомат на другом конце коридора не имеет
 * права звучать так же, как автомат, у которого стоишь. Полноценный
 * позиционный звук (PannerNode, HRTF) здесь не нужен и был бы вреден:
 * камера свободно вращается вокруг персонажа, и панорама, посчитанная
 * по мировым координатам, при повороте камеры разъехалась бы со сценой —
 * звук справа на экране пошёл бы в левое ухо. Расстояние же от поворота
 * камеры не зависит, поэтому затухание — единственная честная половина
 * позиционного звука, и берётся она целиком.
 *
 * Слушатель — персонаж, а не камера. Игрок отождествляет себя с фигуркой,
 * и отъезд камеры не должен делать мир тише.
 */

/** Радиус, внутри которого звук идёт в полную силу. Метры. */
export const NEAR_METERS = 2

/**
 * Радиус, за которым источник не слышен вовсе. Метры.
 *
 * Двадцать два — это длина коридора этажа (24 клетки по метру минус
 * стены). Смысл в том, что звук с одного конца коридора до другого
 * доходит на пределе слышимости, а не пропадает на середине.
 */
export const FAR_METERS = 22

export function distanceBetween(a: Vec2, b: Vec2): number {
  const dx = a.x - b.x
  const dz = a.z - b.z
  return Math.hypot(dx, dz)
}

/**
 * Множитель громкости для источника на заданном расстоянии.
 *
 * Внутри `near` — единица, за `far` — ноль, между ними — обратная
 * пропорция (как в физике: вдвое дальше — вдвое тише), домноженная
 * на линейный спад к нулю. Одна обратная пропорция не годится: она
 * не обращается в ноль никогда, и далёкий автомат вечно шуршал бы
 * на пороге слышимости, а таких автоматов на этаже несколько.
 */
export function distanceGain(
  distance: number,
  near: number = NEAR_METERS,
  far: number = FAR_METERS,
): number {
  if (!Number.isFinite(distance) || distance <= near) return 1
  if (distance >= far) return 0
  const inverse = near / distance
  const rolloff = 1 - (distance - near) / (far - near)
  return inverse * rolloff
}

/**
 * Громкость звука, случившегося в точке `source`, для слушателя
 * в точке `listener`. `at === null` — звук без места: щелчок в интерфейсе,
 * звонок с пары, оценка. Такие звучат в полную силу всегда.
 */
export function positionalGain(listener: Vec2, source: Vec2 | null): number {
  if (source === null) return 1
  return distanceGain(distanceBetween(listener, source))
}
