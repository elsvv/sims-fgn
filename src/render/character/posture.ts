/**
 * Поза человека и всё, что в ней считается числами.
 *
 * Здесь нет ни three, ни react — только геометрия и время, поэтому всё
 * это проверяется тестом, а не глазами на скриншоте. Как именно повороты
 * ложатся на кости модели — в seatedPose.ts; как на капсулы — прямо
 * в ProceduralCharacter.tsx.
 *
 * ПОЧЕМУ ПОЗА СЧИТАЕТСЯ, А НЕ БЕРЁТСЯ ИЗ КЛИПА. В наборе Quaternius
 * Ultimate Modular двадцать четыре клипа, и сидения среди них нет вовсе.
 * Готовое сидение есть в Universal Animation Library того же автора, но
 * скелеты у наборов разные, и не «немного»: у моделей кости зовутся
 * `Hips`, `UpperLegL`, `WristL`, у библиотеки — `pelvis`, `thigh_l`,
 * `hand_l`. Общее имя во всех 62 и 65 костях ровно одно — `Head`.
 * Дорожка клипа адресует кость по имени, поэтому клип из библиотеки
 * на модель не ложится никак: он просто не находит, что вращать.
 * Подробности и что с этим делать — research/assets-characters.md, §7.3.
 */

/** Чем занят человек с точки зрения того, кто его рисует. */
export type Posture = 'stand' | 'walk' | 'sit'

/**
 * За сколько секунд человек садится и встаёт.
 *
 * Это не анимация вставания, а переход между двумя позами, и он нарочно
 * заметно медленнее перехода между стоянием и ходьбой: человек, мгновенно
 * оказавшийся сидящим, выглядит не севшим, а телепортировавшимся.
 */
export const SIT_FADE_SECONDS = 0.45

/**
 * Насколько тазобедренный сустав выше плоскости сиденья, в метрах.
 *
 * Не ноль: сустав сидит внутри таза, а не на коже, и на стуле человек
 * держится на мягких тканях бедра. Восемь сантиметров — половина
 * толщины бедра взрослого человека.
 */
export const HIP_ABOVE_SEAT = 0.08

/** Наклон корпуса вперёд у сидящего, радианы. */
export const SEATED_LEAN = 0.1

/** Плечо у сидящего чуть подано вперёд, предплечье лежит на бедре. Радианы. */
export const SEATED_UPPER_ARM = 0.22
export const SEATED_FOREARM = 0.95

/**
 * На сколько опустить фигуру, чтобы она села на сиденье такой высоты.
 *
 * Считается от таза, а не от макушки: стоя и сидя у человека совпадает
 * не рост, а место, которым он касается опоры. Отрицательного ответа
 * не бывает — на барный стул с высоким сиденьем человек не «поднимается»
 * сам собой, он на него залезает, а такой мебели в игре нет.
 *
 * @param standingHip высота тазобедренного сустава стоя, метры
 * @param seatHeight высота сиденья над полом, метры
 */
export function seatedDrop(standingHip: number, seatHeight: number): number {
  return Math.max(0, standingHip - (seatHeight + HIP_ABOVE_SEAT))
}

/** Углы ног сидящего: оба отсчитываются от вертикали. */
export interface SeatedLegAngles {
  /** Насколько бедро отведено вперёд, радианы. 0 — нога висит отвесно. */
  thigh: number
  /** Насколько голень отклонена назад, радианы. 0 — голень отвесна. */
  shin: number
}

/**
 * Как согнуть ногу, чтобы сидящий доставал ступнёй до пола.
 *
 * Задача школьная, но её нельзя решить константой: рост у шестерых разный,
 * длины костей масштабируются вместе с ним, а высота сиденья — свойство
 * мебели. Человек ростом 1.63 на том же стуле сидит иначе, чем ростом 1.83,
 * и «повернуть бедро на 80°» верно ровно для одного из них.
 *
 * Решение: бедро уходит вперёд ровно настолько, чтобы отвесная голень
 * достала до пола. Если сиденье низкое и голень оказалась длиннее просвета,
 * бедро кладётся горизонтально, а голень уезжает вперёд — так и садятся
 * на низкое. Если сиденье высокое и ноги до пола не достают, они просто
 * висят отвесно: это честно, именно так сидят на высоком.
 *
 * @param hip высота тазобедренного сустава сидящего над полом, метры
 * @param ankle высота щиколотки над полом, метры (у стоящего)
 * @param thigh длина бедра, метры
 * @param shin длина голени, метры
 */
export function seatedLegAngles(options: {
  hip: number
  ankle: number
  thigh: number
  shin: number
}): SeatedLegAngles {
  const { hip, ankle, thigh, shin } = options
  const gap = hip - ankle
  if (thigh <= 0 || shin <= 0 || !Number.isFinite(gap)) return { thigh: 0, shin: 0 }

  const byThigh = (gap - shin) / thigh
  // Просвет больше вытянутой ноги: ступня до пола не дойдёт при любом сгибе.
  if (byThigh >= 1) return { thigh: 0, shin: 0 }
  // Просвет короче одной голени: бедро горизонтально, голень уходит вперёд.
  if (byThigh <= 0) {
    const byShin = Math.min(1, Math.max(-1, gap / shin))
    return { thigh: Math.PI / 2, shin: Math.acos(byShin) }
  }
  return { thigh: Math.acos(byThigh), shin: 0 }
}

/**
 * Доля веса позы сидения после очередного кадра.
 *
 * Отдельной функцией — потому что это единственное место, где поза
 * зависит от времени, и единственное, что можно испортить незаметно:
 * вес, выехавший за единицу, вывернет фигуру наизнанку.
 */
export function blendTowards(current: number, target: number, seconds: number): number {
  const step = SIT_FADE_SECONDS > 0 ? seconds / SIT_FADE_SECONDS : 1
  const moved = current < target
    ? Math.min(target, current + step)
    : Math.max(target, current - step)
  return Math.min(1, Math.max(0, moved))
}

/* ---------------------------------------------------------------------- *
 * Дыхание
 * ---------------------------------------------------------------------- */

/** Полный вдох-выдох, секунды. Четырнадцать в минуту — покой взрослого. */
export const BREATH_PERIOD_SECONDS = 4.3

/** Насколько дыхание качает корпус, радианы, и насколько поднимает, метры. */
export const BREATH_BEND = 0.014
export const BREATH_LIFT = 0.005

/**
 * Фаза дыхания, −1..1.
 *
 * Сдвиг постоянен для человека и случаен между людьми: шестеро, дышащих
 * в такт, — это не живой этаж, а кордебалет. Тем же сдвигом разводится
 * и клип стояния (см. GltfCharacter).
 */
export function breathPhase(seconds: number, offset: number): number {
  return Math.sin(((seconds / BREATH_PERIOD_SECONDS + offset) % 1) * Math.PI * 2)
}

/* ---------------------------------------------------------------------- *
 * Частота обновления анимаций
 * ---------------------------------------------------------------------- */

/**
 * До какого расстояния анимация считается каждый кадр, метры.
 * Дальше человека всё равно видно, но подмену тридцати кадров в секунду
 * на десять на таком расстоянии уже не отличить.
 */
export const ANIMATION_NEAR_METRES = 18
export const ANIMATION_FAR_METRES = 30

/** Сколько раз в секунду пересчитывается анимация у дальних. */
const MIDDLE_HZ = 30
const FAR_HZ = 12

/**
 * Через сколько секунд можно обновлять анимацию человека, стоящего
 * на таком расстоянии от камеры. Ноль — каждый кадр.
 *
 * Зачем это нужно. Каждый человек на этаже — это шестьдесят две кости,
 * которые надо проинтерполировать и перемножить, и делать это для того,
 * кто занимает на экране двадцать пикселей в конце коридора, незачем.
 * Людей на этаже семеро, а будет десяток — и это как раз тот случай,
 * когда дешевле заложить меру заранее, чем потом искать, почему просело.
 *
 * Пропущенный кадр не съедается: накопленное время отдаётся проигрывателю
 * целиком, поэтому дальний человек шагает медленнее по кадрам, но ровно
 * с той же скоростью по времени. Иначе он отставал бы от собственных ног.
 */
export function animationStepSeconds(distanceMetres: number): number {
  if (!(distanceMetres > ANIMATION_NEAR_METRES)) return 0
  if (distanceMetres <= ANIMATION_FAR_METRES) return 1 / MIDDLE_HZ
  return 1 / FAR_HZ
}
