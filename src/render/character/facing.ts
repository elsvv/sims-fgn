/**
 * Куда повёрнута фигура на экране.
 *
 * Правило одно на всех, и это главное: и капсульный человечек, и модель
 * из набора поворачиваются одной и той же функцией. Разъехаться они не
 * могут — разъехаться может только поправочный угол, а он объявлен рядом
 * и проверен тестом на все четыре стороны.
 *
 * Как считается. Симуляция хранит направление взгляда как
 * `facing = atan2(dz, dx)`: ноль смотрит вдоль +X, четверть оборота —
 * вдоль +Z. Единичный вектор взгляда в мире — `(cos facing, sin facing)`
 * по осям (x, z).
 *
 * Модель в своих координатах смотрит вдоль +Z. Повёрнутая на угол `yaw`
 * вокруг вертикали, она смотрит в мир как `(sin yaw, cos yaw)`. Приравняв
 * одно другому, получаем `yaw = π/2 − facing`.
 *
 * Поправочный угол нужен, если модель смотрит не вдоль +Z. Тогда её
 * собственный «перёд» сначала доворачивается на `offset`, и уравнение
 * становится `yaw + offset = π/2 − facing`.
 */

/**
 * На сколько модель из набора Quaternius смотрит мимо +Z.
 *
 * Ноль — и это проверено, а не предположено: у всех моделей набора
 * лицо, носки ботинок и грудь смотрят вдоль +Z, ровно как у капсульного
 * человечка. Константа существует не потому, что сейчас что-то нужно
 * поворачивать, а потому что при замене набора поворачивать придётся,
 * и тогда правится одно число, а не два компонента.
 */
export const GLTF_FACING_OFFSET = 0

/** Поправочный угол капсульного человечка: он изначально собран лицом вдоль +Z. */
export const PROCEDURAL_FACING_OFFSET = 0

/**
 * Поворот фигуры вокруг вертикали.
 *
 * @param facing направление взгляда из симуляции, atan2(dz, dx)
 * @param offset на сколько «перёд» модели отклонён от +Z
 */
export function characterYaw(facing: number, offset: number): number {
  return Math.PI / 2 - facing - offset
}

/**
 * Куда фигура смотрит в мире после поворота. Нужна тесту: он сверяет
 * направление взгляда с направлением движения, а не два угла между собой.
 *
 * @returns единичный вектор в плоскости пола, оси (x, z)
 */
export function facingDirection(yaw: number, offset: number): { x: number; z: number } {
  return { x: Math.sin(yaw + offset), z: Math.cos(yaw + offset) }
}
