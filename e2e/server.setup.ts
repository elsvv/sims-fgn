import { expect, test } from '@playwright/test'

/**
 * По адресу отвечает наша игра, а не соседский проект.
 *
 * Проверка стоит первой и от неё зависят все остальные (см. проекты
 * в playwright.config.ts). Смысл — превратить непонятное падение
 * в понятное.
 *
 * Как это выглядит без неё. `reuseExistingServer` разрешает playwright
 * взять уже поднятый сервер по тому же адресу — и он его берёт, не
 * спрашивая, чьё приложение там живёт. Если 5173 занят соседним
 * проектом на vite, все восемь проверок уходят смотреть чужую страницу
 * и падают на `expect(canvas).toBeVisible()` с текстом «element(s) not
 * found». По этому тексту разбираются полчаса и обычно не туда: ищут
 * поломку в рендере, которой нет.
 *
 * Держимся за <title>: он в index.html, меняется раз в жизни и уникален.
 * Канвас для этой цели не годится — WebGL на программном рендерере
 * поднимается небыстро, и его отсутствие в первую секунду ещё ничего
 * не значит.
 */
test('по адресу отвечает эта игра, а не соседний проект', async ({ page, baseURL }) => {
  await page.goto('/')

  const title = await page.title()
  expect(
    title,
    `На ${baseURL} отвечает не эта игра, а «${title}». Скорее всего, порт занят ` +
      'чужим dev-сервером: vite со --strictPort не поднялся, а playwright взял ' +
      'чужой. Запустите на свободном порту: PORT=5180 npm run e2e',
  ).toBe('Симс ФГН')
})
